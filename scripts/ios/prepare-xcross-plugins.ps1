param([Parameter(Mandatory = $true)][string]$CachePath)

# xcross 2.0.9 emits a Swift registrant using this plugin's Objective-C name.
# qr_code_scanner_plus 2.3.0 exposes a different Swift type with that @objc name.
# Add an alias to the generated registrant module; leave package sources intact.
$ErrorActionPreference = 'Stop'
$resolvedCache = (Resolve-Path -LiteralPath $CachePath).Path
$allowedRoot = [IO.Path]::GetFullPath((Join-Path $env:LOCALAPPDATA 'xcross\swiftpm')) + [IO.Path]::DirectorySeparatorChar
if (-not $resolvedCache.StartsWith($allowedRoot, [StringComparison]::OrdinalIgnoreCase)) {
    throw 'Expected an xcross SwiftPM cache under LocalAppData'
}
$moduleDirectory = Join-Path $resolvedCache 'plugins\Plugins\Sources\FlutterPluginsGenerated'
$registryFile = Join-Path $moduleDirectory 'GeneratedPluginRegistrant.swift'
$qrSource = Join-Path $resolvedCache 'plugins\Packages\qr_code_scanner_plus\ios\qr_code_scanner_plus\Sources\qr_code_scanner_plus\SwiftFlutterQrPlusPlugin.swift'
if ((Get-Content -LiteralPath $registryFile -Raw) -notmatch 'FlutterQrPlusPlugin\.register\(with: registrar\)') {
    throw 'Expected QR registration is absent; reassess this compatibility alias'
}
if ((Get-Content -LiteralPath $qrSource -Raw) -notmatch 'public class SwiftFlutterQrPlusPlugin') {
    throw 'Expected public Swift QR class is absent'
}
if ((Get-Item -LiteralPath $moduleDirectory).Attributes -band [IO.FileAttributes]::ReparsePoint) {
    throw 'Refusing to write through a linked generated module directory'
}
$aliasFile = Join-Path $moduleDirectory 'ChatLoomPluginAliases.swift'
$aliasSource = "// Local xcross compatibility alias; generated by ChatLoom scripts/ios.`nimport qr_code_scanner_plus`ntypealias FlutterQrPlusPlugin = SwiftFlutterQrPlusPlugin`n"
if ((Test-Path -LiteralPath $aliasFile) -and (Get-Content -LiteralPath $aliasFile -Raw) -ne $aliasSource) {
    throw 'An unexpected compatibility file already exists; refusing overwrite'
}
[IO.File]::WriteAllText($aliasFile, $aliasSource, [Text.UTF8Encoding]::new($false))
Write-Output 'Prepared QR Swift registration alias in the generated xcross module.'
